"""Derive launcher variants from the approved vector and existing light color palettes.

Run from any directory: python3 tools/generate-launcher-ring-icons.py
The monochrome drawable is always the original ic_fuel.xml, never a colored variant.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
res = root / "app/src/main/res"
vector = (res / "drawable/ic_fuel.xml").read_text()
vector = vector[vector.index("<vector"):]
palettes = (root / "app/src/main/java/mx/fuelstatus/ui/ColorPalettes.kt").read_text()
colors = {"android": "@android:color/system_accent1_100"}
for palette in ["Blue", "Violet", "Rose", "Orange", "Gray"]:
    block = re.search(rf"private val {palette}Light = lightColorScheme\((.*?)\n\)", palettes, re.S)[1]
    colors[palette.lower()] = "#" + re.search(r"primaryContainer = Color\(0xFF([0-9A-F]{6})\)", block)[1]
for code, color in colors.items():
    foreground = vector.replace('android:strokeColor="#D4EEB1"', f'android:strokeColor="{color}"')
    (res / f"drawable/ic_fuel_ring_{code}.xml").write_text(
        "<!-- Generated by tools/generate-launcher-ring-icons.py. -->\n" + foreground)
    (res / f"mipmap-anydpi/ic_launcher_{code}.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate-launcher-ring-icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@android:color/white" />
    <foreground android:drawable="@drawable/ic_fuel_ring_{code}" />
    <monochrome android:drawable="@drawable/ic_fuel" />
</adaptive-icon>
''')
