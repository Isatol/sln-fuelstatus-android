// npm install --prefix /tmp/fuelstatus-colors --ignore-scripts @material/material-color-utilities@0.3.0
// node tools/generate-theme-palettes.mjs /tmp/fuelstatus-colors/node_modules/@material/material-color-utilities/index.js
import {writeFileSync} from 'node:fs';
import {fileURLToPath, pathToFileURL} from 'node:url';

const {Hct, SchemeTonalSpot, SchemeMonochrome, MaterialDynamicColors, argbFromHex} =
  await import(pathToFileURL(process.argv[2]).href);
const seeds = {Green: '#43672F', Blue: '#1565C0', Violet: '#6750A4', Rose: '#AD4168', Orange: '#A65316', Gray: '#777777'};
const roles = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceTint', 'inverseSurface', 'inverseOnSurface', 'error', 'onError', 'errorContainer', 'onErrorContainer',
  'outline', 'outlineVariant', 'scrim', 'surfaceBright', 'surfaceDim', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest', 'surfaceContainerLow', 'surfaceContainerLowest',
  'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
  'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
  'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant'];
let out = `// Generated by tools/generate-theme-palettes.mjs with Material Color Utilities 0.3.0.
// Tonal Spot (Monochrome for Gray), contrast level 0; no runtime dependency.
package mx.fuelstatus.ui

import androidx.compose.material3.*
import androidx.compose.ui.graphics.Color
import mx.fuelstatus.domain.ThemePalette

internal fun paletteColorScheme(palette: ThemePalette, dark: Boolean): ColorScheme = when (palette) {
${Object.keys(seeds).map(name => `    ThemePalette.${name} -> if (dark) ${name}Dark else ${name}Light`).join('\n')}
}

`;
for (const [name, seed] of Object.entries(seeds)) {
  for (const dark of [false, true]) {
    const scheme = new (name === 'Gray' ? SchemeMonochrome : SchemeTonalSpot)(Hct.fromInt(argbFromHex(seed)), dark, 0);
    out += `private val ${name}${dark ? 'Dark' : 'Light'} = ${dark ? 'dark' : 'light'}ColorScheme(\n`;
    for (const role of roles) {
      const argb = MaterialDynamicColors[role].getArgb(scheme);
      out += `    ${role} = Color(0x${(argb >>> 0).toString(16).toUpperCase()}),\n`;
    }
    out += ')\n\n';
  }
}
writeFileSync(fileURLToPath(new URL('../app/src/main/java/mx/fuelstatus/ui/ColorPalettes.kt', import.meta.url)), out.trimEnd() + '\n');
